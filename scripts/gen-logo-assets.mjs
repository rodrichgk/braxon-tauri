// Regenerates the raster logo assets that can't live as source SVG:
//
//   1. src/lib/pdfLogos.ts  ->  BRAXON_WORDMARK_PNG   (white wordmark for the
//      dark PDF report header band; jsPDF only takes PNG/JPEG, not SVG)
//   2. app-icon.png         ->  1024x1024 black app-icon source, from which
//      `npm run tauri icon app-icon.png` rebuilds src-tauri/icons/*
//   3. app-icon.svg         ->  the matching vector source (kept in sync so
//      the repo's icon source actually corresponds to what ships)
//
// The single source of truth for the mark + wordmark geometry is
// src/components/Logo.tsx — this script scrapes the <path d> data straight
// out of the LogoSymbol / LogoName components so the two never drift.
//
// Run:  npm run gen:logos      (then, for the OS icon set:
//        npm run tauri icon app-icon.png)

import fs from 'node:fs';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';

const ROOT = path.resolve(import.meta.dirname, '..');
const LOGO_TSX = path.join(ROOT, 'src/components/Logo.tsx');
const PDF_LOGOS = path.join(ROOT, 'src/lib/pdfLogos.ts');
const APP_ICON_PNG = path.join(ROOT, 'app-icon.png');
const APP_ICON_SVG = path.join(ROOT, 'app-icon.svg');

const INK = '#111113'; // near-black — matches --color-text-primary
const WORDMARK_FILL = '#f5f5f7'; // sits on the report's near-black header band

/** Pull viewBox, the single <g transform>, and every <path d> out of one component. */
function scrapeComponent(src, fnName) {
  const start = src.indexOf(`export function ${fnName}`);
  if (start < 0) throw new Error(`${fnName} not found in Logo.tsx`);
  const chunk = src.slice(start, src.indexOf('\n}', start));
  const viewBox = chunk.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const transform = chunk.match(/<g transform="([^"]+)"/)[1];
  const paths = [...chunk.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, ' ').trim());
  return { viewBox, transform, paths };
}

const buildSvg = ({ viewBox, transform, paths }, fill, vb = viewBox) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}">` +
  `<g transform="${transform}" fill="${fill}">` +
  paths.map((d) => `<path d="${d}"/>`).join('') +
  `</g></svg>`;

/** Tight content box of an SVG, in viewBox units, via an alpha scan of a render. */
function contentBox(svg, viewBox) {
  const img = new Resvg(svg, { fitTo: { mode: 'width', value: 1600 } }).render();
  const { pixels, width, height } = img; // raw RGBA
  let minX = width, minY = height, maxX = -1, maxY = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (pixels[(width * y + x) * 4 + 3] > 8) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  const sx = viewBox[2] / width;
  const sy = viewBox[3] / height;
  return { x: minX * sx, y: minY * sy, w: (maxX - minX) * sx, h: (maxY - minY) * sy };
}

const src = fs.readFileSync(LOGO_TSX, 'utf8');
const wordmark = scrapeComponent(src, 'LogoName');
const symbol = scrapeComponent(src, 'LogoSymbol');

// ── 1. BRAXON wordmark PNG (white, transparent, cropped tight) ──────────────
{
  const box = contentBox(buildSvg(wordmark, WORDMARK_FILL), wordmark.viewBox);
  const pad = 6; // viewBox units of breathing room
  const vb = [box.x - pad, box.y - pad, box.w + pad * 2, box.h + pad * 2];
  const svg = buildSvg(wordmark, WORDMARK_FILL, vb);
  const rendered = new Resvg(svg, { fitTo: { mode: 'width', value: 2600 } }).render();
  const b64 = `data:image/png;base64,${Buffer.from(rendered.asPng()).toString('base64')}`;

  let out = fs.readFileSync(PDF_LOGOS, 'utf8');
  const nl = out.includes('\r\n') ? '\r\n' : '\n';
  const decl = `export const BRAXON_WORDMARK_PNG = ${JSON.stringify(b64)};`;
  const marker = /export const BRAXON_WORDMARK_PNG = "[^"]*";/;
  const comment = '// BRAXON wordmark, white on transparent — regenerated by scripts/gen-logo-assets.mjs';
  if (marker.test(out)) {
    out = out.replace(marker, decl);
  } else {
    const anchor = /export const BRAXON_ICON_PNG = "[^"]*";\r?\n/;
    if (!anchor.test(out)) throw new Error('BRAXON_ICON_PNG anchor not found in pdfLogos.ts');
    out = out.replace(anchor, (m) => `${m}${nl}${comment}${nl}${decl}${nl}`);
  }
  fs.writeFileSync(PDF_LOGOS, out);
  console.log(`pdfLogos.ts  BRAXON_WORDMARK_PNG  ${rendered.width}x${rendered.height}  ${(b64.length / 1024).toFixed(1)} KB`);
}

// ── 2 & 3. Black app icon: SVG source + 1024 PNG for `tauri icon` ───────────
{
  const box = contentBox(buildSvg(symbol, '#fff'), symbol.viewBox);
  const S = 1024;
  const R = 224; // corner radius (~22%)
  const markH = S * 0.6; // mark fills 60% of the icon height
  const scale = markH / box.h;
  const markW = box.w * scale;
  const tx = (S - markW) / 2 - box.x * scale;
  const ty = (S - markH) / 2 - box.y * scale;

  const iconSvg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">` +
    `<rect width="${S}" height="${S}" rx="${R}" ry="${R}" fill="${INK}"/>` +
    `<g transform="translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${scale.toFixed(6)})">` +
    `<g transform="${symbol.transform}" fill="#ffffff">` +
    symbol.paths.map((d) => `<path d="${d}"/>`).join('') +
    `</g></g></svg>`;

  fs.writeFileSync(APP_ICON_SVG, iconSvg + '\n');
  const png = new Resvg(iconSvg, { fitTo: { mode: 'width', value: S } }).render().asPng();
  fs.writeFileSync(APP_ICON_PNG, png);
  console.log(`app-icon.svg + app-icon.png  ${S}x${S}  (run: npm run tauri icon app-icon.png)`);
}
